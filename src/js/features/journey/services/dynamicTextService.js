import { calculateCoachPositions, getSectorsForCoaches } from '../../formation/formationUtils.js';
import { formatDisplayName } from '../trainNumberFormatter.js';
import { JourneyCouplingService } from './journeyCouplingService.js';
import { JourneyViaService } from './journeyViaService.js';
import { AUTO_INFO_TEXT_TYPES, ANSCHLUSSTAFEL_TEXT_TYPES } from './infoTextTypes.js';
import { calculateDelayMinutes, parseTimeToMinutes, formatTimeFromMinutes } from '../../../core/utils/dateUtils.js';

/**
 * Service für die Erzeugung und Aktualisierung dynamischer Lauftext-Bausteine
 * (Ankunftskontext und Zugteilungs-/Schwächungshinweise).
 */
export class DynamicTextService {
    /**
     * Generiert den Text "Ankunft [Zeit] (heute ca. [Zeit]) als [Linie] von [Start]".
     * @param {object} departureJourney - Die ausgehende Abfahrt
     * @param {object} arrivalJourney - Die verknüpfte Ankunfts-Fahrt
     * @returns {string} Der generierte Präfix
     */
    static generateArrivalContextText(departureJourney, arrivalJourney) {
        if (!arrivalJourney || !departureJourney) return '';

        // Bei echten Durchfahrten (gleiche HAFAS journeyId) generieren wir keinen "Kommt aus..." Text
        if (departureJourney.journeyId && arrivalJourney.journeyId && departureJourney.journeyId === arrivalJourney.journeyId) {
            return '';
        }

        let text = `Ankunft ${arrivalJourney.scheduledTime}`;

        // Verspätung berechnen & auf volle 5 Minuten abrunden
        if (arrivalJourney.expectedTime && arrivalJourney.expectedTime !== arrivalJourney.scheduledTime) {
            const delay = calculateDelayMinutes(arrivalJourney.scheduledTime, arrivalJourney.expectedTime);
            if (delay >= 5) {
                const planMin = parseTimeToMinutes(arrivalJourney.scheduledTime);
                if (planMin !== null) {
                    const roundedDelay = Math.floor(delay / 5) * 5;
                    const roundedExpectedTime = formatTimeFromMinutes(planMin + roundedDelay);
                    text += ` (heute ca. ${roundedExpectedTime})`;
                }
            }
        }

        // Liniennummer vergleichen (mittels formatDisplayName für NRW-Modus / Linienfilterung)
        const arrivalLine = formatDisplayName(arrivalJourney.effectiveDisplayName, true);
        const depLine = formatDisplayName(departureJourney.effectiveDisplayName, true);

        if (arrivalLine && arrivalLine !== depLine) {
            text += ` als ${arrivalLine}`;
        }

        // Herkunft (destination bei Ankunft ist "von")
        const origin = arrivalJourney.destinationKurz || arrivalJourney.destination;
        if (origin) {
            text += ` von ${origin}`;
        }

        return text;
    }

    /**
     * Synchronisiert dynamisch generierte Infotexte (Ankunftstext, Zugteilung)
     * als verwaltbare Bausteine im infoTexts-Array der jeweiligen Journey.
     * @param {Array} journeys - Alle Journeys
     * @param {object} platform - Das Platform-Objekt des aktuellen Bahnhofs/Gleises
     * @param {string|null} [stationName=null] - Name des aktuellen Bahnhofs (für Zugteilungstexte)
     */
    static sync(journeys, platform, stationName = null) {
        for (const journey of journeys) {
            const upsertText = (type, text) => {
                const isAutoType = ANSCHLUSSTAFEL_TEXT_TYPES.has(type);

                // Vom Nutzer gelöschter Auto-Text?
                if (isAutoType && journey.suppressedInfoTextTypes?.includes(type)) {
                    if (!text) {
                        // Bedingung entfällt → Unterdrückung aufheben, damit der
                        // Text bei erneutem Auftreten wieder erscheinen kann.
                        journey.suppressedInfoTextTypes =
                            journey.suppressedInfoTextTypes.filter(t => t !== type);
                    }
                    return;
                }

                const existing = journey.infoTexts.find(t => t.type === type);

                if (text) {
                    if (existing) {
                        // Manuell bearbeitete Auto-Texte nicht überschreiben
                        if (isAutoType && existing.manualOverride) return;
                        // Nur bei echter Änderung schreiben, um Reaktivitäts-Spam zu vermeiden
                        if (existing.text !== text) existing.text = text;
                        if (isAutoType && existing.autoGenerated === undefined) {
                            existing.autoGenerated = true;
                        }
                    } else {
                        const newText = {
                            id: crypto.randomUUID(),
                            text: text,
                            visible: true,
                            type: type,
                            ...(isAutoType ? { autoGenerated: true, manualOverride: false } : {})
                        };
                        // Auto-Texte hinten anhängen (Editor-Reihenfolge bleibt erhalten),
                        // bestehende Kontexttexte behalten ihr bisheriges unshift-Verhalten.
                        if (isAutoType) {
                            journey.infoTexts.push(newText);
                        } else {
                            journey.infoTexts.unshift(newText);
                        }
                    }
                } else if (existing) {
                    // Nur automatisch generierte, nicht manuell überschriebene Texte entfernen
                    if (isAutoType && existing.manualOverride) return;
                    journey.infoTexts = journey.infoTexts.filter(t => t !== existing);
                }
            };

            // 1. Ankunftstext
            let arrivalText = "";
            if (!journey.ankunft && journey.linkedArrivalJourneyId) {
                const arrival = journeys.find(j => j.id === journey.linkedArrivalJourneyId);
                if (arrival) {
                    arrivalText = this.generateArrivalContextText(journey, arrival);
                }
            }
            upsertText('arrival-context', arrivalText);

            // 2. Schwächungstext (Zugteil endet in...)
            let strengtheningText = "";
            if (!journey.ankunft && !journey.infoscreen && !journey.hasTrackChange && !journey.ausfall && journey.verkehrtAb === "0") {
                const group = JourneyCouplingService.expandCoupling(journeys, journey);
                const primaryDest = (journey.destination || "").trim();
                const primaryDestLang = journey.destinationLang || journey.destination;

                if (group.length === 1 && journey.formation && journey.formation.groups && journey.formation.groups.length > 1) {
                    const { allCoaches } = calculateCoachPositions(group);

                    let texts = [];
                    for (let i = 0; i < journey.formation.groups.length; i++) {
                        const formationGroup = journey.formation.groups[i];
                        const groupDest = (formationGroup.destination || "").trim();

                        if (groupDest && groupDest !== primaryDest && groupDest !== primaryDestLang) {
                            const nrwName = formatDisplayName(formationGroup.trainNumber || journey.name, true);
                            const targetCoaches = allCoaches.filter(item => item.group === formationGroup);
                            const sectors = getSectorsForCoaches(targetCoaches, platform);

                            if (sectors) {
                                const sectorParts = sectors.split('-');
                                const firstSection = sectorParts[0];
                                const lastSection = sectorParts.length > 1 ? sectorParts[1] : null;
                                const deSectionText = lastSection ? `in den Abschnitten ${firstSection} bis ${lastSection}` : `im Abschnitt ${firstSection}`;
                                const enSectionText = lastSection ? `in sections ${firstSection} to ${lastSection}` : `in section ${firstSection}`;
                                texts.push(`Zugteil ${nrwName} ${deSectionText} endet in ${groupDest} +++ Train segment ${nrwName} ${enSectionText} ends in ${groupDest}`);
                            } else {
                                texts.push(`Zugteil ${nrwName} endet in ${groupDest} +++ Train segment ${nrwName} ends in ${groupDest}`);
                            }
                        }
                    }
                    if (texts.length > 0) {
                        strengtheningText = texts.join(' +++ ');
                    }
                }
            }
            upsertText('strengthening', strengtheningText);

            // 3. Zugteilungstext (Zugteilung in...) für gekoppelte Fahrten mit unterschiedlichen Zielen
            let splitText = "";
            if (!journey.ankunft && !journey.infoscreen && !journey.hasTrackChange && !journey.ausfall && journey.verkehrtAb === "0") {
                const group = JourneyCouplingService.expandCoupling(journeys, journey);
                if (group.length > 1 && !JourneyCouplingService.areJourneysMerged(group)) {
                    splitText = JourneyCouplingService.generateSplitText(group, stationName || null);
                }
            }
            upsertText('wing-split', splitText);

            // 4. Haltbezogene Meldungen aus der Halteliste
            upsertText(AUTO_INFO_TEXT_TYPES.NO_CONTINUATION, this._buildNoContinuationText(journey));
            upsertText(AUTO_INFO_TEXT_TYPES.SKIPPED_STOPS, this._buildSkippedStopsText(journey));
            upsertText(AUTO_INFO_TEXT_TYPES.ADDITIONAL_STOPS, this._buildAdditionalStopsText(journey));
        }
    }

    // ==========================================
    // Haltbezogene Auto-Texte
    // ==========================================

    /**
     * Liefert alle Halte nach dem aktuellen Halt.
     * @param {object} journey
     * @returns {Array}
     */
    static _futureStops(journey) {
        const start = journey._currentStopIndex >= 0
            ? journey._currentStopIndex + 1
            : 0;
        return (journey.stops || []).slice(start);
    }

    /**
     * Anzeigename eines Halts (Kurzname bevorzugt).
     * @param {object} stop
     * @returns {string}
     */
    static _stopName(stop) {
        return stop?.nameKurz || stop?.name || '';
    }

    /**
     * Geplanter Endbahnhof ohne Fallback 'Ziel'.
     * @param {object} journey
     * @returns {string}
     */
    static _plannedDestination(journey) {
        return journey.destinationOverride
            || journey.destinationLang
            || journey.destination
            || '';
    }

    /**
     * Verbindet Teile deutsch: "A", "A und B", "A, B und C".
     * @param {string[]} parts
     * @returns {string}
     */
    static _joinGerman(parts) {
        if (parts.length === 0) return '';
        if (parts.length === 1) return parts[0];
        if (parts.length === 2) return `${parts[0]} und ${parts[1]}`;
        return `${parts.slice(0, -1).join(', ')} und ${parts[parts.length - 1]}`;
    }

    /**
     * Erzeugt "Keine Weiterfahrt nach Z", wenn der letzte zukünftige Halt
     * ausgefallen ist und der Zielbahnhof dadurch nicht mehr erreicht wird.
     * @param {object} journey
     * @returns {string}
     */
    static _buildNoContinuationText(journey) {
        if (journey.ankunft || journey.infoscreen || journey.ausfall) return '';
        if (!journey.stops || journey.stops.length === 0) return '';

        const future = this._futureStops(journey);
        if (future.length === 0) return '';

        const lastStop = future[future.length - 1];
        if (!lastStop.cancelled) return '';

        // Letzten noch bedienten Halt inkl. aktuellem Halt finden
        const allRelevant = journey.stops.slice(
            journey._currentStopIndex >= 0 ? journey._currentStopIndex : 0
        );
        const lastActive = [...allRelevant].reverse().find(s => !s.cancelled);
        if (!lastActive) return '';

        // Ziel wurde bereits erreicht → kein "Keine Weiterfahrt"
        if (JourneyViaService.isDestinationStop(journey, lastActive)) return '';

        const destination = this._plannedDestination(journey);
        return destination ? `Keine Weiterfahrt nach ${destination}` : '';
    }

    /**
     * Erzeugt "Ohne Halt in …" aus zusammenhängenden ausgefallenen zukünftigen
     * Halten. Der Zielbahnhof wird ausgelassen (dafür gibt es "Keine Weiterfahrt").
     * @param {object} journey
     * @returns {string}
     */
    static _buildSkippedStopsText(journey) {
        if (journey.ankunft || journey.infoscreen || journey.ausfall) return '';
        if (!journey.stops || journey.stops.length === 0) return '';

        const future = this._futureStops(journey);
        const relevant = future.filter(
            s => !JourneyViaService.isDestinationStop(journey, s)
        );
        if (relevant.length === 0) return '';

        const runs = [];
        let currentRun = [];

        for (const stop of relevant) {
            if (stop.cancelled) {
                currentRun.push(stop);
            } else if (currentRun.length > 0) {
                runs.push(currentRun);
                currentRun = [];
            }
        }
        if (currentRun.length > 0) runs.push(currentRun);

        if (runs.length === 0) return '';

        const formattedRuns = runs.map(run => {
            const names = run.map(s => this._stopName(s)).filter(Boolean);
            if (names.length === 0) return '';
            if (names.length === 1) return names[0];
            if (names.length === 2) return `${names[0]} und ${names[1]}`;
            return `${names[0]} bis ${names[names.length - 1]}`;
        }).filter(Boolean);

        if (formattedRuns.length === 0) return '';
        return `Ohne Halt in ${this._joinGerman(formattedRuns)}`;
    }

    /**
     * Erzeugt "Zusätzlicher Halt in …" aus zukünftigen Zusatzhalten.
     * Es wird nie "bis" verwendet.
     * @param {object} journey
     * @returns {string}
     */
    static _buildAdditionalStopsText(journey) {
        if (journey.ankunft || journey.infoscreen || journey.ausfall) return '';

        const additional = this._futureStops(journey)
            .filter(s => s.additional && !s.cancelled);

        if (additional.length === 0) return '';

        const names = additional.map(s => this._stopName(s)).filter(Boolean);
        if (names.length === 0) return '';

        return `Zusätzlicher Halt in ${this._joinGerman(names)}`;
    }
}
